function y_shift = desloca_inicio(y)

    idx = find(y ~= 0, 1);

    if isempty(idx)
        y_shift = y;
        return;
    end

    % garante início em zero físico
    y_shift = zeros(size(y));

    len = length(y) - idx + 1;

    if len > 1
        y_shift(2:len) = y(idx:end-1);
    end

    y_shift(1) = 0;
end

